"""Integration tests for the module generated by generate_parameter_module().

The generated module is loaded into a live ROS 2 node that is configured from
config/implementation.yaml, the parameter file shipped with this example. This
keeps the example config consistent with the parameter definition: a required
parameter added to the parameter definition without updating the config file
fails these tests. config/missing_required.yaml is used to check the opposite
direction: a config that omits a required parameter is rejected at runtime.
"""

import os
import unittest

import rclpy
from rclpy.exceptions import ParameterUninitializedException
from rclpy.node import Node
from rclpy.parameter import Parameter

from cmake_generate_parameter_module_example.admittance_parameters import (
    admittance_controller,
)

CONFIG_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'config')


class GeneratedModuleFromConfigTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        config = os.path.join(CONFIG_DIR, 'implementation.yaml')
        rclpy.init(args=['--ros-args', '--params-file', config])
        cls.node = Node(
            'admittance_controller',
            automatically_declare_parameters_from_overrides=True,
        )
        cls.listener = admittance_controller.ParamListener(cls.node)
        cls.params = cls.listener.get_params()

    @classmethod
    def tearDownClass(cls):
        cls.node.destroy_node()
        rclpy.shutdown()

    def test_scalar_and_array_values_from_config(self):
        self.assertEqual(
            self.params.joints,
            [
                'shoulder_pan_joint',
                'shoulder_lift_joint',
                'elbow_joint',
                'wrist_1_joint',
                'wrist_2_joint',
                'wrist_3_joint',
            ],
        )
        self.assertEqual(self.params.command_interfaces, ['position'])
        self.assertEqual(self.params.state_interfaces, ['position', 'velocity'])
        self.assertEqual(self.params.fixed_string_no_default, 'happy')
        self.assertEqual(
            self.params.fixed_string_array_no_default,
            ['alpha', 'beta', 'gamma', 'delta', 'epsilon'],
        )

    def test_nested_struct_values_from_config(self):
        self.assertEqual(self.params.kinematics.tip, 'ee_link')
        self.assertEqual(self.params.kinematics.base, 'base_link')
        self.assertAlmostEqual(self.params.kinematics.alpha, 0.0005)
        self.assertAlmostEqual(self.params.admittance.mass[0], 3.0)
        self.assertEqual(self.params.admittance.stiffness, [50.0] * 3 + [1.0] * 3)

    def test_map_values_from_config(self):
        self.assertAlmostEqual(self.params.pid.get_entry('shoulder_pan_joint').i, 0.7)
        self.assertAlmostEqual(self.params.pid.get_entry('wrist_3_joint').i, 0.5)

    def test_map_entries_match_parameter_server(self):
        for joint in self.params.joints:
            for field in ('p', 'i', 'd'):
                param_name = f'pid.{joint}.{field}'
                lib_value = getattr(self.params.pid.get_entry(joint), field)
                ros_value = self.node.get_parameter(param_name).value
                self.assertAlmostEqual(
                    lib_value,
                    ros_value,
                    msg=f'Mismatch for {param_name}: {lib_value} != {ros_value}',
                )
        for dof in self.params.dof_names:
            for field in ('weight', 'limit'):
                param_name = f'elbow_joint.{dof}.{field}'
                lib_value = getattr(
                    self.params.get_entry('elbow_joint').get_entry(dof), field
                )
                ros_value = self.node.get_parameter(param_name).value
                self.assertEqual(
                    lib_value,
                    ros_value,
                    msg=f'Mismatch for {param_name}: {lib_value} != {ros_value}',
                )

    def test_default_value_used_when_config_silent(self):
        self.assertEqual(self.params.interpolation_mode, 'spline')

    def test_parameter_update_reaches_module(self):
        self.node.set_parameters([Parameter('interpolation_mode', value='linear')])
        updated_params = self.listener.get_params()
        self.assertEqual(updated_params.interpolation_mode, 'linear')


class IncompleteConfigRejectedTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.config = os.path.join(CONFIG_DIR, 'missing_required.yaml')
        rclpy.init(args=['--ros-args', '--params-file', cls.config])

    @classmethod
    def tearDownClass(cls):
        rclpy.shutdown()

    def test_missing_required_parameter_raises(self):
        node = Node(
            'admittance_controller',
            automatically_declare_parameters_from_overrides=True,
        )
        try:
            with self.assertRaises(ParameterUninitializedException):
                admittance_controller.ParamListener(node)
        finally:
            node.destroy_node()
